/**
 * 生日 → 星座。
 *
 * 接受「YYYY-MM-DD」与「MM-DD」两种写法（注册表单给年月日，其他入口可能只给月日）。
 * 解析不出来就返回 null，**不抛错也不猜一个默认星座** —— 生日是可选信息，
 * 「没填/填错」和「填了白羊座」在界面上是两种完全不同的展示，不能混为一谈。
 *
 * 只比较「月-日」，不比较年份：星座只跟太阳在黄道上的位置有关。
 * 摩羯座跨年（12-22 到 01-19），所以区间判断要分成「不跨年」和「跨年」两种，
 * 不能简单地写 from <= x && x <= to。
 */
export function signFromBirthday(birthday: string): ZodiacSign | null {
  if (typeof birthday !== "string") return null;
  const match = /^(?:\d{4}-)?(\d{2})-(\d{2})$/.exec(birthday.trim());
  if (!match) return null;

  const month = Number(match[1]);
  const day = Number(match[2]);
  // 只认日历上真实存在的月日。2 月放到 29 天：闰年的 02-29 是有效生日，
  // 而「某年是不是闰年」跟星座判定无关，为此把年份也拖进来判断没有意义。
  const maxDay = [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31][month - 1];
  if (maxDay === undefined || day < 1 || day > maxDay) return null;

  const key = `${match[1]}-${match[2]}`;
  return (
    ZODIAC_SIGNS.find((sign) =>
      sign.from <= sign.to
        ? key >= sign.from && key <= sign.to
        : // 跨年：摩羯座 12-22 ~ 01-19，落在区间外的两侧都算命中
          key >= sign.from || key <= sign.to,
    ) ?? null
  );
}
