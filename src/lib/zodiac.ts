/**
 * 黄道十二星座的星点布局
 * ══════════════════════════════════════════════════════════════════
 *
 * 纯数据 + 一个日期查表函数，**不碰数据库、不碰 React** —— 和 constellation.ts
 * 一样，它必须能被 node --test 直接加载（所以没有任何 import），也必须完全确定
 * （同一个星座每次画出来都得一模一样，星图不能被「随机」污染）。
 *
 * ── 坐标从哪来 ──────────────────────────────────────────────
 *
 * x/y 不是随手摆的，是**真实亮星的赤经赤纬投影**：
 * 以该星座主要亮星的中心为原点，赤经按 `cos(赤纬)` 压缩（球面在赤道附近
 * 一度赤经与一度赤纬等长，越靠极区越短，不压缩会把星座横向拉长），
 * 再等比缩放铺满画布、四周留 0.08 的边距。
 * 取北在上、东在左 —— 这是天文星图的惯例，也是抬头看南天时看到的方向。
 * 所以狮子座的镰刀是反写的问号、天蝎座的尾巴朝东南弯、金牛座是一个张口的 V。
 *
 * ── 为什么每颗星要带 magnitude 而不是只给坐标 ─────────────────
 *
 * 星图上的「亮」是练出来的：星等由打卡推算（见 constellation.ts 的 starMagnitude）。
 * 布局里的 magnitude 是这颗星**本身**的亮度，取真实视星等折算到 0..1，
 * 用来决定底图上这颗星该多大 —— 心宿二就该比尾宿三显眼，否则星座不像星座。
 *
 * ── stars 的顺序 = 点亮顺序（这条最容易被忽略）─────────────────
 *
 * 用户是逐次打卡、一颗一颗点亮星图的。顺序按星座轮廓**从头到尾走一遍**
 * （多数星座是一条一笔画得出来的链），星图就会像有人在慢慢描线；
 * 若按坐标排序或随机排，用户看到的是一堆点在乱蹦。
 * 分叉的图形（双子座是两个人、室女座有手臂和裙摆）一笔画不完，
 * 这时顺序会在分支之间跳一次 —— 跳的落点都挑在图形内部的近邻之间，
 * 不会横穿整个星座。
 *
 * ── simple 与 full 的关系 ───────────────────────────────────
 *
 * simple 是给「学习计划简单」的用户看的：只留最主要的那几颗（5~7 枚），
 * 形状仍然认得出。**simple 的星严格是 full 的子集，坐标逐位相同**，
 * 所以从 simple 升到 full 时，原有星点不会挪位，只是旁边多长出暗星来 ——
 * 用户升级计划不该看到自己的星图整个跳一下。这一点由测试锁死。
 *
 * ── 已知取舍（如实记录，方便以后校对）───────────────────────
 *
 * 1. 只收「让形状更像」的亮星，5.5 等以下基本不进：更暗的星不会让轮廓更清楚，
 *    只会让画面变脏。个别必要位置（如巨蟹座的鬼宿一/二）留了 5 等出头的暗星。
 * 2. 金牛座的昴宿星团只在真实位置上放了 3 枚成员（昴宿六/七/二）。星团本身
 *    只有 1° 出头，在这个尺度下它们会挤在一起 —— 那是事实，不是画错。
 * 3. 坐标是**等比投影**，没有为了好看而拉伸：细长的星座（双鱼、水瓶、处女）
 *    只撑满画布的一条轴，另一条轴留白。强行拉方会让形状走样，宁可留白。
 * 4. 天蝎座、狮子座这些一笔画得下来的星座，点亮顺序是完整的一条链；
 *    双子、室女、双鱼是分叉图形，顺序里有 1~2 次跳跃，跳距都控制在内部。
 */

/** 一个星点在星座里的位置，坐标是 0..1 的归一化值 */
export type ZodiacStar = {
  x: number; // 0..1
  y: number; // 0..1
  magnitude: number; // 0..1，越大越亮（真实亮星给 0.7~1.0，暗星 0.25~0.5）
  name?: string; // 该星的真实名字，如「心宿二」「轩辕十四」，没有就不填
};

/** 一套星点布局 */
export type ZodiacPattern = {
  /** **顺序有意义**：星星按这个数组顺序依次点亮，所以要按描线顺序排 */
  stars: ZodiacStar[];
  /** 连线，元素是上面 stars 的下标对 */
  links: Array<[number, number]>;
};

export type ZodiacSign = {
  key: string; // "aries" | "taurus" | ... 12 个，全小写英文
  name: string; // "白羊座"
  nameEn: string; // "Aries"
  /** 生日落在哪一段算这个星座，闭区间，格式 "MM-DD" */
  from: string; // 如 "03-21"
  to: string; // 如 "04-19"
  /** 简约档：5~7 枚星，用于学习计划简单的用户 */
  simple: ZodiacPattern;
  /** 完整档：9~14 枚星，用于计划复杂的用户 */
  full: ZodiacPattern;
};

